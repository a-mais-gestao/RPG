const fs = require('fs');
const src = fs.readFileSync(__dirname + '/app.js','utf8');
const tests = [];
const ok = (name, cond) => tests.push({name, pass:!!cond});
ok('Ramo social pode iniciar conflito', src.includes('const shouldConflict=!!branch.conflictOnFail || (action.id===\'intimidate\' && !!r.fumble);'));
ok('Falha crítica de intimidação gera conflito', src.includes("action.id==='intimidate' && !!r.fumble"));
ok('Contexto de retorno do diálogo é salvo', src.includes("type:'npc-dialogue',npcId:n.id,poiIndex:returnPoiIndex"));
ok('Hex selecionado é preservado', src.includes("cell:Number(state.map.selected)"));
ok('PV do NPC é sincronizado ao encerrar', src.includes("n.hp=Math.max(0,Math.min(n.maxHp||999,state.combat.beast.hp))"));
ok('Estado do NPC é atualizado', src.includes("n.status=n.hp<=0?'Incapacitado':'Ativo'"));
ok('Retorno passa pelo mapa', src.includes("show('map');setTimeout(()=>"));
ok('Diálogo do NPC é reaberto', src.includes("interactMapNPC(idx,npcId)"));
ok('POI permanece em andamento durante conflito', src.includes("mapPOIResult(key,shouldConflict?`${result} O diálogo fica em andamento até o conflito terminar.`:result,shouldConflict?'andamento':'concluido')"));
ok('Resultado flutuante de encerramento é preparado', src.includes("title:'Conflito com NPC encerrado'"));
ok('JavaScript possui endCombat válido', /function endCombat\(\)\{[\s\S]*?\}/.test(src));
const failed=tests.filter(t=>!t.pass);
console.log(tests.map(t=>`${t.pass?'PASS':'FAIL'} - ${t.name}`).join('\n'));
console.log(`\n${tests.length-failed.length}/${tests.length} verificações passaram.`);
if(failed.length)process.exit(1);
